"""Generate src/label_font.inc: flattened glyph outlines for symmetry labels.

Development-time only. Reads the DejaVu Sans and STIX General Italic TrueType
files bundled with Matplotlib and writes polygon outlines in 1/1000 em units,
so that QASR itself needs no font library or font file at run time."""
import argparse
import os
from pathlib import Path

import matplotlib
from matplotlib import ft2font
from matplotlib.ft2font import FT2Font
from matplotlib.path import Path as MPath

ROOT=Path(__file__).resolve().parents[1]
FONTS=[('sans','DejaVuSans.ttf','DejaVu Sans'),('italic','STIXGeneralItalic.ttf','STIX General Italic')]
CODES=list(range(32,127))+[0xc5,0x3c3]
STEPS=5


def flatten(vertices,codes):
    contours=[];current=[];i=0
    def bezier(points):
        start=current[-1]
        for k in range(1,STEPS+1):
            t=k/STEPS;p=[start]+points
            while len(p)>1:p=[((1-t)*a[0]+t*b[0],(1-t)*a[1]+t*b[1]) for a,b in zip(p,p[1:])]
            current.append(p[0])
    while i<len(codes):
        code=codes[i]
        if code==MPath.MOVETO:
            if len(current)>2:contours.append(current)
            current=[tuple(vertices[i])];i+=1
        elif code==MPath.LINETO:current.append(tuple(vertices[i]));i+=1
        elif code==MPath.CURVE3:bezier([tuple(vertices[i]),tuple(vertices[i+1])]);i+=2
        elif code==MPath.CURVE4:bezier([tuple(vertices[i]),tuple(vertices[i+1]),tuple(vertices[i+2])]);i+=3
        else:i+=1  # CLOSEPOLY
    if len(current)>2:contours.append(current)
    return contours


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'src/label_font.inc')
    args=parser.parse_args()
    directory=Path(matplotlib.get_data_path())/'fonts/ttf'
    no_scale=getattr(ft2font,'LOAD_NO_SCALE',None) or ft2font.LoadFlags.NO_SCALE
    out=['/* Generated by tools/build_label_font.py; do not edit.',
         ' * Glyph outlines flattened to polygons in 1/1000 em, y upward from the baseline.',
         ' * sans: DejaVu Sans (Bitstream Vera/Arev license). italic: STIX General Italic',
         ' * (STIX Font License). See THIRD_PARTY_NOTICES.md. */']
    for name,file,title in FONTS:
        font=FT2Font(str(directory/file),hinting_factor=1);scale=1000/font.units_per_EM
        points=[];contours=[];glyphs=[]
        for code in CODES:
            if not font.get_char_index(code):raise SystemExit(f'{title} lacks U+{code:04X}')
            glyph=font.load_char(code,flags=no_scale);vertices,codes=font.get_path();vertices=vertices*64  # 26.6 fixed point
            first=len(contours)
            for contour in flatten(vertices,codes):
                rounded=[]
                for x,y in contour:
                    p=(round(x*scale),round(y*scale))
                    if not rounded or p!=rounded[-1]:rounded.append(p)
                if len(rounded)>1 and rounded[0]==rounded[-1]:rounded.pop()
                if len(rounded)<3:continue
                contours.append((len(points),len(rounded)));points.extend(rounded)
            glyphs.append((code,round(glyph.horiAdvance*scale),first,len(contours)-first))
        font.load_char(ord('H'),flags=no_scale);vertices,_=font.get_path();vertices=vertices*64
        cap=round(max(v[1] for v in vertices)*scale)
        out.append(f'/* {title}: {len(glyphs)} glyphs, {len(contours)} contours, {len(points)} points. */')
        out.append(f'static const int16_t label_{name}_points[][2]={{')
        for k in range(0,len(points),12):out.append(' '+','.join(f'{{{x},{y}}}' for x,y in points[k:k+12])+',')
        out.append('};')
        out.append(f'static const LabelContour label_{name}_contours[]={{')
        for k in range(0,len(contours),10):out.append(' '+','.join(f'{{{a},{n}}}' for a,n in contours[k:k+10])+',')
        out.append('};')
        out.append(f'static const LabelGlyph label_{name}_glyphs[]={{')
        for k in range(0,len(glyphs),6):out.append(' '+','.join(f'{{{c},{a},{f},{n}}}' for c,a,f,n in glyphs[k:k+6])+',')
        out.append('};')
        out.append(f'static const LabelFont label_{name}={{label_{name}_glyphs,sizeof label_{name}_glyphs/sizeof *label_{name}_glyphs,'
                   f'label_{name}_contours,label_{name}_points,{cap}}};')
    args.output.write_text('\n'.join(out)+'\n')


if __name__=='__main__':
    main()
